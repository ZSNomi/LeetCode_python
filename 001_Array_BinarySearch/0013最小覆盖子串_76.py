# 1:字符valid的实质：
# 其实，valid 这个变量记录的是每一种字符是否达到了所需的频次要求。
# 比如，如果 t 中需要 2 个 'A'，但当前窗口只扫描到了 1 个 'A'，说明 'A' 的数量还不够。此时，'A' 这个字符还不算达标，所以 valid 加 1 的条件不会被触发（进度条不能前进）。
# 只有当窗口里收集到了 2 个 'A' 时，说明 'A' 的数量已经达标了。在这之后，不管再往窗口里添加多少个 'A'，都不会影响 valid 了，因为我们只需要看其他还没达标的字符什么时候能满足条件。
# 假设 t 中有 3 种不同的字符（比如 A、B、C），那么这 3 种字符都需要分别满足各自所需的频次。只有当这 3 种字符全部达标（各加 1），valid 才能累加到 3。此时 valid == len(need)（即所需字符的种类数），就说明当前窗口已经完全满足要求了。


